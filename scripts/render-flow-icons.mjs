// The icon list behind every icon setting. Two steps, run after changing `ICONS` in widgets/spacer/public/kit.js or
// scripts/lucide-icons.json (our id → Lucide's name; a new id also needs `flows.icons.<id>` in every locale):
// `npm run flow-icons`.
//  1. widgets/spacer/public/icons.js: the icons from Lucide (lucide-static, pinned) as one path each, as the kit's are.
//  2. lib/flowIconImages.ts: a preview of every icon as a PNG data URL, since the phone apps draw an item's `image` as a
//     bitmap and showed nothing for an SVG (iOS, 2026-10-08).
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import sharp from 'sharp';

const SIZE = 96; // 3x a 32 px row image
const LUCIDE = 'node_modules/lucide-static';

/** A number as short as it can be written, for a path. */
const n = value => String(Math.round(Number(value) * 1000) / 1000);

/**
 * A path's first `m` is an absolute position only while it starts its own path: joined to another path it would move
 * from where that one ended (Lucide's `m2 2 20 20`), and the numbers after it are relative lines. So: `M2 2l20 20`.
 */
function absoluteStart(d) {
  const number = '[-+]?(?:\\d*\\.\\d+|\\d+\\.?)(?:e[-+]?\\d+)?';
  const m = d.trim().match(new RegExp(`^m\\s*(${number})[\\s,]*(${number})[\\s,]*(.*)$`, 's'));
  if (!m) return d.trim();
  const [, x, y, rest] = m;
  return `M${x} ${y}${rest && !/^[a-z]/i.test(rest) ? 'l' : ''}${rest}`;
}

/** One SVG element as path commands: Lucide's shapes draw the same as these (checked by rendering both). */
function toPath(tag, a) {
  const num = (key, fallback = 0) => (a[key] === undefined ? fallback : Number(a[key]));
  const points = () => a.points.trim().split(/[\s,]+/).map(Number);
  const ellipse = (cx, cy, rx, ry) => `M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(2 * rx)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-2 * rx)} 0z`;
  switch (tag) {
    case 'path': return absoluteStart(a.d);
    case 'circle': return ellipse(num('cx'), num('cy'), num('r'), num('r'));
    case 'ellipse': return ellipse(num('cx'), num('cy'), num('rx'), num('ry'));
    case 'line': return `M${n(num('x1'))} ${n(num('y1'))}L${n(num('x2'))} ${n(num('y2'))}`;
    case 'polyline':
    case 'polygon': {
      const p = points();
      const line = p.reduce((s, v, i) => s + (i % 2 ? ` ${n(v)}` : `${i ? 'L' : 'M'}${n(v)}`), '');
      return tag === 'polygon' ? `${line}z` : line;
    }
    case 'rect': {
      const [x, y, w, h] = [num('x'), num('y'), num('width'), num('height')];
      const rx = Math.min(num('rx', num('ry')), w / 2), ry = Math.min(num('ry', num('rx')), h / 2);
      if (!rx || !ry) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
      const arc = (dx, dy) => `a${n(rx)} ${n(ry)} 0 0 1 ${n(dx)} ${n(dy)}`;
      return `M${n(x + rx)} ${n(y)}h${n(w - 2 * rx)}${arc(rx, ry)}v${n(h - 2 * ry)}${arc(-rx, ry)}h${n(2 * rx - w)}${arc(-rx, -ry)}v${n(2 * ry - h)}${arc(rx, -ry)}z`;
    }
    default: throw new Error(`Lucide: no conversion for <${tag}>`);
  }
}

/** A Lucide icon's SVG file as the one path the widgets draw. An icon that isn't all plain strokes is refused. */
function lucidePath(name) {
  const svg = readFileSync(`${LUCIDE}/icons/${name}.svg`, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const body = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1];
  const parts = [...body.matchAll(/<(\w+)\s([^>]*?)\/>/g)].map(([, tag, attrs]) => {
    const a = Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
    const extra = Object.keys(a).filter(k => !['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points'].includes(k));
    if (extra.length) throw new Error(`Lucide ${name}: <${tag}> has ${extra.join(', ')}`);
    return toPath(tag, a);
  });
  if (!parts.length) throw new Error(`Lucide ${name}: nothing to draw`);
  return parts.join('');
}

// 1. The file with the icons from Lucide.
const { version } = JSON.parse(readFileSync(`${LUCIDE}/package.json`, 'utf8'));
const chosen = JSON.parse(readFileSync('scripts/lucide-icons.json', 'utf8'));
const entries = Object.entries(chosen).map(([id, name]) => `    ${id}: { d: ${JSON.stringify(lucidePath(name))} },`);
writeFileSync('widgets/spacer/public/icons.js', `/* Generated by scripts/render-flow-icons.mjs (\`npm run flow-icons\`) from scripts/lucide-icons.json; don't edit.
 * The rest of the icon settings' icons, on top of the kit's: every page whose widgets can show one loads this after the kit.
 * Lucide ${version} (https://lucide.dev), ISC and, for the icons from Feather, MIT: see icons.LICENSE.txt. */
(() => {
  Object.assign(window.WidgetkeeperKit.icons, {
${entries.join('\n')}
  });
})();
`);
copyFileSync(`${LUCIDE}/LICENSE`, 'widgets/spacer/public/icons.LICENSE.txt');

// 2. The previews, with the kit's icons first; `more`: from Lucide, listed once someone searches.
const win = {};
const context = vm.createContext({ window: win });
vm.runInContext(readFileSync('widgets/spacer/public/kit.js', 'utf8'), context);
const icons = win.WidgetkeeperKit.icons;
const common = new Set(Object.keys(icons));
vm.runInContext(readFileSync('widgets/spacer/public/icons.js', 'utf8'), context);

const lines = [];
for (const [id, icon] of Object.entries(icons)) {
  // The widget's button: the white glyph, 18 of 32 px, on Homey's blue.
  const paint = icon.fill ? 'fill="#fff"'
    : 'fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 32 32">`
    + '<circle cx="16" cy="16" r="16" fill="#2F8DF6"/>'
    + `<path transform="translate(7 7) scale(.75)" d="${icon.d}" ${paint}/></svg>`;
  const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: true }).toBuffer();
  lines.push(`  ${id}: { d: ${JSON.stringify(icon.d)}, ${common.has(id) ? '' : 'more: true, '}image: 'data:image/png;base64,${png.toString('base64')}' },`);
}

writeFileSync('lib/flowIconImages.ts', `// Generated by scripts/render-flow-icons.mjs (\`npm run flow-icons\`); don't edit.
// The icons as PNG data URLs for the settings' previews. \`d\` is the path each was drawn from, so a test notices when
// the widget's icons change and this wasn't re-rendered. \`more\`: not in the kit, so listed once someone searches.
export const FLOW_ICON_IMAGES: Record<string, { d: string, more?: boolean, image: string }> = {
${lines.join('\n')}
};
`);
console.log(`${lines.length} icons (${lines.length - common.size} from Lucide ${version}) → widgets/spacer/public/icons.js, lib/flowIconImages.ts`);
