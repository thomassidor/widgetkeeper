// Bundles qrcode-generator (MIT) into settings/qrcode.js for the app settings page (settings/index.html), which draws
// a screen's address as a QR code (Web dashboards, Screens). Served by the Homey itself, so the page needs nothing
// from the internet. Run it after updating qrcode-generator: `npm run qr-code`.
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';

const { version } = JSON.parse(readFileSync('node_modules/qrcode-generator/package.json', 'utf8'));

await build({
  stdin: { contents: "window.qrcode = require('qrcode-generator');", resolveDir: '.', loader: 'js' },
  bundle: true,
  format: 'iife',
  platform: 'browser',
  minify: true,
  legalComments: 'none',
  banner: { js: `/* Generated by scripts/build-qr-code.mjs (\`npm run qr-code\`); don't edit. qrcode-generator ${version} (MIT). */` },
  outfile: 'settings/qrcode.js',
  logLevel: 'info',
});
