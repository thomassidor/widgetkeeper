// Renders the kit's capability glyphs (`valueGlyph()`) for the autocomplete rows of device values into
// lib/valueGlyphImages.ts: PNG data URLs, since the phone apps draw an item's `image` as a bitmap and showed nothing for
// an SVG (iOS, 2026-10-08). Run it after changing `VALUE_GLYPHS` in widgets/spacer/public/kit.js: `npm run value-glyphs`.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import sharp from 'sharp';

const SIZE = 64; // 2x a 32 px row: a list has up to 100 of them, and a chosen row's image is kept in the widget's settings

const win = {};
const context = vm.createContext({ window: win, btoa });
vm.runInContext(readFileSync('widgets/spacer/public/kit.js', 'utf8'), context);
const kit = win.WidgetkeeperKit;

// A capability that gets each glyph (`test/value-glyphs.test.ts` holds the same glyphs against lib/valueGlyphs.ts).
const GLYPHS = {
  thermometer: ['measure_temperature'], drop: ['measure_humidity'], bolt: ['measure_power'], sun: ['measure_luminance'],
  cloud: ['measure_co2'], battery: ['measure_battery'], bell: ['alarm_motion'], power: ['onoff'], locked: ['locked', true],
  unlocked: ['locked', false], bulb: ['dim'], wave: ['measure_noise'], gauge: ['anything'],
};

const lines = [];
for (const [name, [capabilityId, value]] of Object.entries(GLYPHS)) {
  const source = kit.valueGlyph(capabilityId, value);
  const inner = Buffer.from(source.split(',')[1], 'base64').toString();
  const [x, y, w, h] = inner.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number);
  const body = inner.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  // The glyph's middle on a neutral circle: a tile's colour isn't the row's, and white on it reads on a light or dark sheet.
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 32 32">`
    + '<circle cx="16" cy="16" r="16" fill="#6B6D78"/>'
    + `<g transform="translate(16 16) scale(.75) translate(${-(x + w / 2)} ${-(y + h / 2)})" fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>`;
  const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: true, colours: 16 }).toBuffer();
  lines.push(`  ${name}: { source: '${source}', image: 'data:image/png;base64,${png.toString('base64')}' },`);
}

writeFileSync('lib/valueGlyphImages.ts', `// Generated by scripts/render-value-glyphs.mjs (\`npm run value-glyphs\`); don't edit.
// The kit's capability glyphs as PNG data URLs for the autocomplete rows. \`source\` is what each was drawn from, so a test
// notices when the kit's glyphs change and this wasn't re-rendered.
export const VALUE_GLYPH_IMAGES: Record<string, { source: string, image: string }> = {
${lines.join('\n')}
};
`);
console.log(`${lines.length} glyphs → lib/valueGlyphImages.ts`);
